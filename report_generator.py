import os
from datetime import datetime
import streamlit as st

def generate_pdf_report(record, fraud_data, validation_data):
    """Generate PDF report and return file path"""
    try:
        # Create filename
        filename = f"report_{record['material_id']}.pdf"
        filepath = os.path.join(os.getcwd(), filename)
        
        # Create a simple PDF using reportlab
        from reportlab.lib.pagesizes import letter
        from reportlab.pdfgen import canvas
        from reportlab.lib.utils import simpleSplit
        
        c = canvas.Canvas(filepath, pagesize=letter)
        width, height = letter
        
        # Title
        c.setFont("Helvetica-Bold", 16)
        c.drawString(50, height - 50, "MTC VERIFICATION REPORT")
        
        # Material ID
        c.setFont("Helvetica-Bold", 12)
        c.drawString(50, height - 80, f"Material ID: {record.get('material_id', 'N/A')}")
        
        # Status with color
        c.setFont("Helvetica-Bold", 14)
        status = record.get('status', 'Unknown')
        if status == "Pass":
            c.setFillColorRGB(0, 0.8, 0)  # Green
        else:
            c.setFillColorRGB(0.8, 0, 0)  # Red
        c.drawString(50, height - 100, f"STATUS: {status}")
        
        # Reset color
        c.setFillColorRGB(0, 0, 0)
        
        # Basic Info
        c.setFont("Helvetica", 12)
        c.drawString(50, height - 130, f"Compliance Score: {record.get('compliance_score', 0):.1f}%")
        c.drawString(50, height - 150, f"Supplier: {record.get('supplier_name', 'Unknown')}")
        c.drawString(50, height - 170, f"Material Grade: {record.get('material_grade', 'Unknown')}")
        c.drawString(50, height - 190, f"Heat Number: {record.get('heat_number', 'Unknown')}")
        c.drawString(50, height - 210, f"Verified By: {record.get('verified_by', 'Unknown')}")
        c.drawString(50, height - 230, f"Date: {datetime.now().strftime('%Y-%m-%d %H:%M')}")
        
        # Validation Results
        c.setFont("Helvetica-Bold", 12)
        c.drawString(50, height - 260, "Validation Results:")
        c.setFont("Helvetica", 10)
        y = height - 280
        if validation_data and 'reasoning' in validation_data:
            for reason in validation_data['reasoning'][:5]:  # Show first 5
                if len(reason) > 80:
                    reason = reason[:77] + "..."
                c.drawString(60, y, f"• {reason}")
                y -= 15
        
        # Fraud Alerts
        if fraud_data and fraud_data.get('alerts'):
            c.setFont("Helvetica-Bold", 12)
            c.drawString(50, y - 10, "Fraud Alerts:")
            c.setFont("Helvetica", 10)
            y2 = y - 30
            for alert in fraud_data['alerts'][:3]:  # Show first 3
                if len(alert) > 80:
                    alert = alert[:77] + "..."
                c.drawString(60, y2, f"⚠️ {alert}")
                y2 -= 15
        
        # Footer
        c.setFont("Helvetica-Oblique", 8)
        c.drawString(50, 50, f"Generated by MTC Verification System - {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")
        
        c.save()
        return filepath
        
    except Exception as e:
        # If PDF generation fails, create a simple text file as fallback
        txt_filename = f"report_{record['material_id']}.txt"
        txt_filepath = os.path.join(os.getcwd(), txt_filename)
        
        with open(txt_filepath, 'w') as f:
            f.write(f"MTC VERIFICATION REPORT\n")
            f.write(f"{'='*50}\n")
            f.write(f"Material ID: {record.get('material_id', 'N/A')}\n")
            f.write(f"Status: {record.get('status', 'Unknown')}\n")
            f.write(f"Compliance Score: {record.get('compliance_score', 0):.1f}%\n")
            f.write(f"Supplier: {record.get('supplier_name', 'Unknown')}\n")
            f.write(f"Grade: {record.get('material_grade', 'Unknown')}\n")
            f.write(f"Heat Number: {record.get('heat_number', 'Unknown')}\n")
        
        return txt_filepath